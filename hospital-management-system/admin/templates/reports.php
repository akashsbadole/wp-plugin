<script type="text/javascript">
jQuery(document).ready(function($) {
    var reportDisplayArea = $('#hms-report-display-area');
    var reportContent = $('#hms-report-content');

    $('.hms-report-form').on('submit', function(e) {
        e.preventDefault();
        var form = $(this);
        var submitButton = form.find('button[type="submit"]');
        var originalButtonText = submitButton.text();

        submitButton.prop('disabled', true).text('<?php esc_html_e('Generating...', 'hospital-management-system'); ?>');
        reportContent.empty();
        reportDisplayArea.hide();

        $.ajax({
            url: ajaxurl,
            type: 'POST',
            data: form.serialize(),
            success: function(response) {
                if (response.success) {
                    reportContent.html(response.data.report_html);
                    reportDisplayArea.show();
                    // Store current report data for export
                    reportContent.data('report-type', form.data('report-type'));
                    reportContent.data('report-params', form.serialize());
                } else {
                    reportContent.html('<div class="notice notice-error"><p>' + response.data + '</p></div>');
                    reportDisplayArea.show();
                }
            },
            error: function() {
                reportContent.html('<div class="notice notice-error"><p><?php esc_html_e('An error occurred while generating the report. Please try again.', 'hospital-management-system'); ?></p></div>');
                reportDisplayArea.show();
            },
            complete: function() {
                submitButton.prop('disabled', false).text(originalButtonText);
            }
        });
    });

    $('#hms-close-report').on('click', function() {
        reportDisplayArea.hide();
        reportContent.empty();
    });

    $('#hms-print-report').on('click', function() {
        var printContents = reportContent.html();
        var originalContents = document.body.innerHTML;
        document.body.innerHTML = printContents;
        window.print();
        document.body.innerHTML = originalContents;
        // Re-initialize scripts if necessary, or simply reload the page
        // location.reload(); 
        // A better approach might be to use a print-specific CSS media query.
        // For simplicity, we'll reload.
        location.reload(); 
    });

    $('#hms-export-csv').on('click', function() {
        var reportType = reportContent.data('report-type');
        var params = reportContent.data('report-params');
        if (!reportType || !params) {
            alert('<?php esc_html_e('No report data to export.', 'hospital-management-system'); ?>');
            return;
        }
        // Add export action to params
        params += '&action=hms_export_report_csv&report_type=' + reportType + '&nonce=<?php echo wp_create_nonce('hms_admin_nonce'); ?>';
        
        // Create a temporary form to submit and trigger download
        var tempForm = $('<form>', {
            'action': ajaxurl,
            'method': 'POST',
            'target': '_blank' // Open in new tab to avoid leaving the page
        }).appendTo('body');
        
        // Add params as hidden fields
        params.split('&').forEach(function(param) {
            var pair = param.split('=');
            $('<input>', {
                'type': 'hidden',
                'name': pair[0],
                'value': pair[1]
            }).appendTo(tempForm);
        });
        
        tempForm.submit().remove();
    });
});
</script>

